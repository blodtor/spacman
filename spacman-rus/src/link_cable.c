/**
 * Link Cable Protocol (LCP) - протокол для обмена данными через SEGA Link Cable
 * между двумя приставками Sega Mega Drive / Sega Genesis, подключаемый во второй порт
 * для SGDK
 *
 * BlodTor 2025 г.
 *
 * *************************************************************************************************
 * *************************************************************************************************
 * Порядок вызова функций на ведущей (master) приставке:
 *
 * 1) Инициализируем Link Cable Protocol.
 * LCP_init();
 *
 * 2) Подготавливаем данные для отправки от ведущей (master) приставки через Link Cable Protocol.
 * LCP_objectToPacketForSend(transferObject, objectType, objectTypeSizes);
 * LCP_objectToPacketForSend(transferObject, objectType, objectTypeSizes);
 * ...
 * LCP_objectToPacketForSend(transferObject, objectType, objectTypeSizes);
 *
 * 3) Вызываем внешнее прерывание на ведомой (slave) приставке, отправляем и получаем данные
 *    через Link Cable Protocol
 * LCP_masterCycle();
 *
 * 4) Извлекаем полученные объекты из пакета, переданного от ведомой (slave) приставки
 * objectType = LCP_getNextObjectFromReceivePacket(transferObject, objectSizes);
 * objectType = LCP_getNextObjectFromReceivePacket(transferObject, objectSizes);
 * ...
 * objectType = LCP_getNextObjectFromReceivePacket(transferObject, objectSizes);
 * пока objectType не станет равным 0
 *
 * 5) Завершаем работу с Link Cable Protocol, если взаимодействие больше не требуется.
 * LCP_close();
 *
 * *************************************************************************************************
 * *************************************************************************************************
 * Порядок вызова функций на ведомой (slave) приставке:
 *
 * 1) Инициализируем Link Cable Protocol
 * LCP_init();
 *
 * 2) Открываем порт, чтобы ведомая (slave) приставка могла обрабатывать внешние прерывания,
 *    вызываемые ведущей (master) приставкой. Ведущая приставка сможет вызывать LCP_slaveCycle() -
 *    обработчик внешнего прерывания на ведомой приставке - только после вызова этого метода.
 * LCP_open();
 *
 * 3) Подготавливаем данные для отправки от ведомой (slave) приставки через Link Cable Protocol.
 *    Отправка происходит в LCP_slaveCycle() после получения данных от ведущей (master) приставки.
 *    LCP_slaveCycle() вызывается асинхронно через приостановку выполнения кода игры на ведомой
 *    приставке при наступлении внешнего прерывания из метода LCP_masterCycle() ведущей приставки.
 * LCP_objectToPacketForSend(transferObject, objectType, objectTypeSizes);
 * LCP_objectToPacketForSend(transferObject, objectType, objectTypeSizes);
 * ...
 * LCP_objectToPacketForSend(transferObject, objectType, objectTypeSizes);
 *
 * 4) Извлекаем полученные объекты из пакета, переданного от ведущей (master) приставки
 * objectType = LCP_getNextObjectFromReceivePacket(transferObject, objectSizes);
 * objectType = LCP_getNextObjectFromReceivePacket(transferObject, objectSizes);
 * ...
 * objectType = LCP_getNextObjectFromReceivePacket(transferObject, objectSizes);
 * пока objectType не станет равным 0
 *
 * 5) Завершаем работу с Link Cable Protocol, если взаимодействие больше не требуется.
 *    Ведомая приставка перестанет реагировать на внешние прерывания от ведущей приставки!
 * LCP_close();
 *
 * *************************************************************************************************
 * *************************************************************************************************
 * ВАЖНЫЕ ЗАМЕЧАНИЯ ПО ИСПОЛЬЗОВАНИЮ:
 * !!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
 *
 * Типы объектов (objectType) должны быть определены в основном коде ВАШЕЙ игры!
 * Смотрите примеры объявления констант в коде игры 'Super Turbo MEGA Pac-Man 2.1',
 * начинающиеся с префикса 'OBJECT_TYPE_'
 *
 * Размеры объектов (objectSizes) в байтах должны быть определены в основном коде ВАШЕЙ игры!
 * За 1 цикл протокол передает 2 байта информации, поэтому нет смысла задавать длину объектов
 * не кратную 2 байтам! Смотрите примеры объявления констант в коде игры 'Super Turbo MEGA Pac-Man 2.1',
 * заканчивающихся постфиксом '_OBJECT_LENGTH', а также пример определения массива LINK_TYPES_LENGHT,
 * который передается как параметр objectSizes в функции LCP_objectToPacketForSend() и
 * LCP_getNextObjectFromReceivePacket()
 *
 * Реализация определения ведущей (master) и ведомой (slave) приставки должна быть в коде ВАШЕЙ игры!
 * Смотрите пример функции initControllerPort2() в коде игры 'Super Turbo MEGA Pac-Man 2.1',
 * которая определяет, какая из двух приставок станет ведущей (master), а какая - ведомой (slave)
 *
 * !!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
 *
 * Для отладки можно использовать функцию, которая возвращает ошибку при передаче данных
 * через SEGA Link Cable:
 * LCP_getError()
 *
 */

#include "types.h"
#include "sys.h"
